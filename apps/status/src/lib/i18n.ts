export type PublicLocale = keyof typeof M;
export type PublicKey = keyof (typeof M)["en"];

export function tr(locale: string) {
  const dict = (M as unknown as Record<string, Record<PublicKey, string>>)[locale] ?? M.en;
  return (key: PublicKey, params: Record<string, string | number> = {}) =>
    String(dict[key]).replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? ""));
}

export function fmtDate(iso: string, locale: string, opts: Intl.DateTimeFormatOptions): string {
  return new Intl.DateTimeFormat(locale === "fr" ? "fr-FR" : locale === "de" ? "de-DE" : "en-GB", {
    timeZone: "Europe/Paris",
    ...opts,
  }).format(new Date(iso));
}

export function relative(iso: string, locale: string): string {
  const diff = Date.now() - new Date(iso).getTime();
  const min = Math.round(diff / 60_000);
  const rtf = new Intl.RelativeTimeFormat(locale === "fr" ? "fr" : locale === "de" ? "de" : "en", {
    numeric: "auto",
  });
  if (Math.abs(min) < 60) return rtf.format(-min, "minute");
  const h = Math.round(min / 60);
  if (Math.abs(h) < 48) return rtf.format(-h, "hour");
  return rtf.format(-Math.round(h / 24), "day");
}

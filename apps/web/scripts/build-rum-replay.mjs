/**
 * Builds the recorder half of the browser SDK from a pinned rrweb.
 *
 * Two decisions are visible here and both were deliberate.
 *
 * **rrweb rather than our own recorder.** A DOM recorder is not hard to start
 * and is very hard to finish: shadow DOM, adopted stylesheets, canvas,
 * cross-origin iframes, `<input type=password>`, web components. A homegrown
 * one records real sites subtly wrong, and the symptom — "the replay looks
 * wrong" — is worse than no replay, because people draw conclusions from it
 * anyway. rrweb is MIT, is what PostHog, Highlight and OpenReplay all record
 * with, and has been wrong in all those places already so we do not have to be.
 *
 * **Generated, never committed.** The output is a build artifact of a pinned
 * version, so it lives in .gitignore and is produced by `predev` and
 * `prebuild`. A 110 kB generated file in git is a file that silently stops
 * matching the version that claims to have produced it.
 *
 * It is a separate file from `oi-rum.js` on purpose, and the numbers are the
 * argument: the base SDK is 6 kB over the wire and loads on every page of
 * every customer; this is 56 kB, nine times that. Only an application that
 * has turned replay on ever fetches it.
 */
import { build } from "esbuild";
import { mkdirSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../public/rum/oi-rum-replay.js");
const version = JSON.parse(
  readFileSync(resolve(here, "../node_modules/rrweb/package.json"), "utf8"),
).version;

mkdirSync(dirname(out), { recursive: true });

await build({
  stdin: {
    contents: `
      import { record } from "rrweb";
      // One global, named like the rest of the SDK's surface. The base file
      // waits for it and starts recording; nothing here starts on its own,
      // because a script that records the moment it is parsed would record
      // pages whose configuration said not to.
      window.openIncidentRumRecord = record;
    `,
    resolveDir: resolve(here, ".."),
    loader: "js",
  },
  bundle: true,
  minify: true,
  format: "iife",
  // The base SDK is ES5 for the browsers that still reach real shops. rrweb
  // does not build to ES5, and es2017 is the floor it is tested against —
  // which is also every browser that has a PerformanceObserver worth reading.
  target: "es2017",
  outfile: out,
  banner: {
    js: `/* Open Incident session replay — bundled from rrweb ${version} (MIT). Generated by scripts/build-rum-replay.mjs; do not edit. */`,
  },
  legalComments: "none",
});

console.log(`rum replay recorder: ${out} (rrweb ${version})`);
